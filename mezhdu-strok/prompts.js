// Ответы человека → текст для промпта.
export function formatAnswers(answers) {
  return QUESTIONS.map((q, i) => {
    const value = (answers[q.id] || '').trim();
    return value ? `${i + 1}. ${q.title}: ${value}` : null;
  }).filter(Boolean).join('\n');
}

export function buildPrompt1(answersText, mode = 'json', sameReason = ENABLE_SAME_REASON) {
  const format = mode === 'json'
    ? FORMAT_JSON + (sameReason ? FORMAT_JSON_SAME_REASON : '')
    : FORMAT_TEXT + (sameReason ? FORMAT_TEXT_SAME_REASON : '');
  return `${PROMPT_1_BODY}\n\n${format}\n\nОТВЕТЫ ЧЕЛОВЕКА:\n${answersText}`;
}

const str = { type: 'string' };
const obj = (properties) => ({
  type: 'object',
  properties,
  required: Object.keys(properties),
  additionalProperties: false,
});

export function resultSchema(sameReason = ENABLE_SAME_REASON) {
  const properties = {
    main_insight: str,
    areas_count: { type: 'integer' },
    patterns: { type: 'array', items: obj({
      title: str,
      description: str,
      evidence: { type: 'array', items: obj({ item: str, reason: str }) },
    }) },
    unexpected_connections: { type: 'array', items: obj({ item_1: str, item_2: str, connection: str }) },
  };
  if (sameReason) properties.same_reason = { type: 'array', items: obj({ item: str, pattern: str }) };
  return obj(properties);
}
